#!/bin/sh
# Domain certificate helpers for native 3x-ui installs.

set -e

XUI_SERVICE_NAME="${XUI_SERVICE_NAME:-x-ui}"
XUI_CERTBOT_DEPLOY_HOOK="${XUI_CERTBOT_DEPLOY_HOOK:-/etc/letsencrypt/renewal-hooks/deploy/restart-x-ui.sh}"

is_domain_name() (
    domain=$1

    [ -n "$domain" ] || return 1
    [ "$domain" != "localhost" ] || return 1

    case "$domain" in
        [0-9]*.[0-9]*.[0-9]*.[0-9]*) return 1 ;;
    esac

    case "$domain" in
        *[!A-Za-z0-9.-]* | .* | *..* | *.) return 1 ;;
    esac

    case "$domain" in
        *.*) return 0 ;;
        *) return 1 ;;
    esac
)

is_placeholder_email() {
    email=$1

    [ -n "$email" ] || return 0

    case "$email" in
        *@example.com|*@example.org|*@example.net|admin@localhost|root@localhost) return 0 ;;
        *@*) return 1 ;;
        *) return 0 ;;
    esac
}

configure_certbot_cli_ini() {
    mkdir -p /etc/letsencrypt
    cli_ini="/etc/letsencrypt/cli.ini"
    if [ ! -f "$cli_ini" ]; then
        echo "# HTTP-01 authenticator/port is selected per certificate by x-ui-fork." > "$cli_ini" 2>/dev/null || true
    elif [ "$(cat "$cli_ini")" = "http-01-port = 8088" ]; then
        # Migrate the old one-line file generated by this fork. Leave custom
        # Certbot configuration untouched.
        echo "# HTTP-01 authenticator/port is selected per certificate by x-ui-fork." > "$cli_ini" 2>/dev/null || true
    fi
}

certbot_issue_domain_cert() (
    # Isolate variables and cleanup traps from the caller (init-config is sourced
    # by several independent systemd entrypoints).
    domain=$1
    email=${2:-}
    additional_domains=${3:-}
    case "$additional_domains" in *[!A-Za-z0-9.,\ -]*)
        echo "[CERT] Additional SAN list contains unsupported characters"; return 1 ;;
    esac

    if ! is_domain_name "$domain"; then
        echo "[CERT] Domain is empty or invalid, skipping certificate issue"
        return 1
    fi

    if ! command -v certbot >/dev/null 2>&1; then
        echo "[CERT] certbot not found, skipping certificate issue"
        return 1
    fi

    cert_path="${XUI_CERTBOT_LIVE_DIR:-/etc/letsencrypt/live}/${domain}/fullchain.pem"
    key_path="${XUI_CERTBOT_LIVE_DIR:-/etc/letsencrypt/live}/${domain}/privkey.pem"
    requested_domains="$domain"
    for candidate in $(printf '%s' "$additional_domains" | tr ',' ' '); do
        if ! is_domain_name "$candidate"; then
            echo "[CERT] Invalid additional DNS name; request cancelled"
            return 1
        fi
        case " $requested_domains " in *" $candidate "*) ;; *) requested_domains="$requested_domains $candidate" ;; esac
    done
    requested_count=$(printf '%s\n' "$requested_domains" | wc -w)
    [ "$requested_count" -le 100 ] || { echo "[CERT] Too many SAN names"; return 1; }
    certificate_ready=0
    if [ -r "$cert_path" ] && [ -r "$key_path" ]; then
        if command -v openssl >/dev/null 2>&1 \
           && openssl x509 -in "$cert_path" -noout -checkend 86400 >/dev/null 2>&1; then
            certificate_ready=1
            for candidate in $requested_domains; do
                if ! openssl x509 -in "$cert_path" -noout -checkhost "$candidate" >/dev/null 2>&1; then
                    certificate_ready=0
                    echo "[CERT] Missing SAN: ${candidate}; certificate ${domain} needs expansion"
                fi
            done
        fi
    fi
    if [ "$certificate_ready" -eq 1 ]; then
        echo "[CERT] Certificate ${domain} covers all requested names — skipping issue"
        return 0
    fi
    # Preserve every existing DNS SAN when expanding. Never silently drop a
    # wildcard/non-DNS identity that this HTTP-01 helper cannot safely reissue.
    if [ -r "$cert_path" ] && command -v openssl >/dev/null 2>&1; then
        san_text=$(openssl x509 -in "$cert_path" -noout -ext subjectAltName 2>/dev/null || true)
        case "$san_text" in
            *'DNS:*'*|*'IP Address:'*|*'URI:'*|*'email:'*)
                echo "[CERT] Existing wildcard/non-DNS SAN requires a separate DNS-01/manual renewal; old certificate kept"
                return 1 ;;
        esac
        unhandled_san=$(printf '%s\n' "$san_text" | sed '1d' | sed -E 's/DNS:[^,[:space:]]+//g' | tr -d ',[:space:]')
        if [ -n "$unhandled_san" ]; then
            echo "[CERT] Existing SAN type cannot be safely preserved by HTTP-01 helper; old certificate kept"
            return 1
        fi
        existing_names=$(printf '%s\n' "$san_text" | grep -oE 'DNS:[^,[:space:]]+' | sed 's/^DNS://' || true)
        for candidate in $existing_names; do
            is_domain_name "$candidate" || { echo "[CERT] Unsafe existing SAN; old certificate kept"; return 1; }
            case " $requested_domains " in *" $candidate "*) ;; *) requested_domains="$requested_domains $candidate" ;; esac
        done
    fi
    requested_count=$(printf '%s\n' "$requested_domains" | wc -w)
    [ "$requested_count" -le 100 ] || { echo "[CERT] Preserved SAN set exceeds certificate limit"; return 1; }

    state_dir="${XUI_CERTBOT_STATE_DIR:-/run/x-ui-certbot}"
    (umask 077; mkdir -p "$state_dir") || return 1
    exec 8>"${state_dir}/issue.lock" || return 1
    if command -v flock >/dev/null 2>&1 && ! flock -n 8; then
        echo "[CERT] Another fork certificate request is running; skipping ${domain}"
        return 1
    fi
    retry_delay="${XUI_CERTBOT_RETRY_DELAY:-300}"
    case "$retry_delay" in ''|*[!0-9]*) retry_delay=300 ;; esac
    [ "${#retry_delay}" -le 6 ] || retry_delay=300
    failure_file="${state_dir}/${domain}.failed"
    now=$(date +%s)
    last_failed=$(cat "$failure_file" 2>/dev/null || echo 0)
    case "$last_failed" in ''|*[!0-9]*) last_failed=0 ;; esac
    [ "${#last_failed}" -le 12 ] || last_failed=0
    if [ "$retry_delay" -gt 0 ] && [ "$now" -ge "$last_failed" ] && [ $((now - last_failed)) -lt "$retry_delay" ]; then
        echo "[CERT] Recent failure for ${domain}; retry cooldown ${retry_delay}s (XUI_CERTBOT_RETRY_DELAY=0 for an explicit retry)"
        return 1
    fi

    # Certbot may also be running outside this helper (timer/manual invocation).
    # Its own lock remains authoritative; never remove .certbot.lock files.
    command -v ss >/dev/null 2>&1 || {
        echo "[CERT] ss is required to inspect port 80 safely"
        return 1
    }
    stopped_service=""
    restore_acme_service() {
        if [ -n "$stopped_service" ]; then
            echo "[CERT] Restoring previously active ${stopped_service}"
            systemctl start "$stopped_service" || true
        fi
    }
    trap restore_acme_service EXIT
    trap 'exit 1' HUP INT TERM

    listeners=$(ss -H -ltnp '( sport = :80 )' 2>/dev/null) || return 1
    owner=""
    if [ -n "$listeners" ] && command -v systemctl >/dev/null 2>&1; then
        for unit in x-ui-decoy.service haproxy.service nginx.service apache2.service httpd.service; do
            systemctl is-active --quiet "$unit" 2>/dev/null || continue
            main_pid=$(systemctl show --property=MainPID --value "$unit" 2>/dev/null || echo 0)
            case "$main_pid" in ''|0|*[!0-9]*) continue ;; esac
            if printf '%s\n' "$listeners" | grep -Eq "pid=${main_pid}(,|\))"; then
                if [ -n "$owner" ]; then
                    echo "[CERT] Multiple services own port 80; refusing to stop them automatically"
                    return 1
                fi
                owner="$unit"
            fi
        done
    fi

    set -- certonly --non-interactive --agree-tos --cert-name "$domain" --expand --preferred-challenges http
    for candidate in $requested_domains; do
        set -- "$@" -d "$candidate"
    done
    if [ "${XUI_PANEL_CONTROLLER_ENABLE:-}" = true ] && [ "${XUI_PANEL_CONTROLLER_CONTEXT:-}" = 1 ]; then
        # The controller reloads its own site/router after validating them.
        # Do not run the fork's global directory hook, which also reloads x-ui.
        set -- "$@" --no-directory-hooks
    fi
    if is_placeholder_email "$email"; then
        set -- "$@" --register-unsafely-without-email
    else
        set -- "$@" --email "$email" --no-eff-email
    fi
    case "$owner" in
        x-ui-decoy.service)
            # Legacy decoy already serves this exact webroot on public HTTP/80.
            # Store the webroot authenticator in the renewal config, avoiding
            # another port-80 collision at certificate renewal time.
            webroot="${XUI_CERTBOT_WEBROOT:-/var/www/html}"
            mkdir -p "$webroot" || return 1
            echo "[CERT] Managed decoy owns port 80; using ACME webroot without stopping it"
            set -- "$@" --webroot --webroot-path "$webroot"
            ;;
        haproxy.service)
            echo "[CERT] HAProxy owns port 80; using its ACME backend on 8088"
            set -- "$@" --standalone --http-01-port 8088
            ;;
        '')
            if [ -n "$listeners" ]; then
                echo "[CERT] Unknown owner of port 80; inspect ss -ltnp before retrying. No services stopped."
                printf '%s\n' "$now" > "$failure_file"
                return 1
            fi
            set -- "$@" --standalone --http-01-port 80
            ;;
        *)
            case "${XUI_CERTBOT_STOP_WEB_SERVER:-false}" in
                true|TRUE|1|yes|YES|on|ON) ;;
                *)
                    echo "[SKIP] ACME не останавливает ${owner}: требуется XUI_CERTBOT_STOP_WEB_SERVER=true либо настройка webroot/DNS-01"
                    printf '%s\n' "$now" > "$failure_file"
                    return 1
                    ;;
            esac
            echo "[CERT] Temporarily stopping port-80 owner ${owner}"
            stopped_service="$owner"
            systemctl stop "$owner" || return 1
            remaining=$(ss -H -ltnp '( sport = :80 )' 2>/dev/null) || return 1
            if [ -n "$remaining" ]; then
                echo "[CERT] Port 80 is still occupied; refusing to stop other services"
                printf '%s\n' "$now" > "$failure_file"
                return 1
            fi
            set -- "$@" --standalone --http-01-port 80
            ;;
    esac

    echo "[CERT] Requesting Let's Encrypt certificate for ${domain}"
    if certbot "$@" && [ -r "$cert_path" ] && [ -r "$key_path" ]; then
        rm -f "$failure_file"
        echo "[CERT] Successfully issued certificate for ${domain}"
        return 0
    else
        printf '%s\n' "$now" > "$failure_file"
        echo "[CERT-WARN] Certificate request failed for ${domain}; no immediate duplicate retry"
        return 1
    fi
)

certbot_install_xui_deploy_hook() {
    hook_path=${1:-$XUI_CERTBOT_DEPLOY_HOOK}
    service_name=${2:-$XUI_SERVICE_NAME}
    hook_dir=$(dirname "$hook_path")

    mkdir -p "$hook_dir"
    cat > "$hook_path" <<EOF
#!/bin/sh
# Reload x-ui and nginx after certificate renewal.
if command -v systemctl >/dev/null 2>&1; then
    if systemctl is-active --quiet nginx 2>/dev/null; then
        systemctl reload nginx 2>/dev/null || true
    fi
    # The decoy has its own nginx master, independent of nginx.service.
    if systemctl is-active --quiet x-ui-decoy.service 2>/dev/null; then
        systemctl reload x-ui-decoy.service 2>/dev/null \
            || systemctl restart x-ui-decoy.service 2>/dev/null \
            || true
    fi
    if systemctl is-active --quiet ${service_name} 2>/dev/null; then
        systemctl kill --kill-who=main -s HUP ${service_name} >/dev/null 2>&1 \
            || systemctl restart ${service_name} >/dev/null 2>&1 \
            || true
    else
        systemctl restart ${service_name} >/dev/null 2>&1 || true
    fi
fi
EOF
    chmod +x "$hook_path"
    echo "[CERT] Deploy hook installed: ${hook_path}"
}

certbot_configure_auto_renewal() {
    configure_certbot_cli_ini
    certbot_install_xui_deploy_hook "$XUI_CERTBOT_DEPLOY_HOOK" "$XUI_SERVICE_NAME"

    if command -v systemctl >/dev/null 2>&1 && systemctl list-unit-files certbot.timer 2>/dev/null | grep -q '^certbot\.timer'; then
        if systemctl enable --now certbot.timer >/dev/null 2>&1; then
            echo "[CERT] Auto-renewal enabled via certbot.timer"
            return 0
        fi
        echo "[CERT] certbot.timer exists but could not be enabled, trying cron"
    fi

    if command -v crontab >/dev/null 2>&1; then
        cron_marker="3x-ui certbot auto-renewal"
        cron_cmd="0 */12 * * * certbot renew --quiet # ${cron_marker}"
        (crontab -l 2>/dev/null | grep -v "$cron_marker" || true; echo "$cron_cmd") | crontab -
        echo "[CERT] Auto-renewal enabled via cron"
        return 0
    fi

    echo "[CERT] No systemd timer or cron found; auto-renewal was not configured"
    return 1
}
